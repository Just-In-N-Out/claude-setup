#!/usr/bin/env bash
# Per-machine Codex install for Justin's setup (story codex-parity). Safe to rerun.
#   setup-codex.sh           build ~/.codex/AGENTS.md and the role files' model lines, link the Hermes
#                            skills into ~/.agents/skills, merge config.managed.toml into
#                            ~/.codex/config.toml (backup first), disable plugin skills that duplicate a
#                            Hermes skill, then check what Codex really loads
#   setup-codex.sh --check   the same checks without writing; exit 0 only when everything is current
# The managed blocks sit between "# >>> claude-setup managed: … >>>" markers: top-level keys before the
# first table, tables at the end. Everything else in config.toml (model, trust, plugins, hook trust,
# MCP servers) is kept as it is. Edit config.managed.toml, never the managed blocks.
# Exit: 0 done, 1 not current (--check), 2 usage or a missing tool, 3 refused (config.toml sets a key
# this script manages; nothing written), 4 a check of what Codex loads failed.
set -uo pipefail
DIR=$(cd "$(dirname "$0")" && pwd)
CH=${CODEX_HOME:-$HOME/.codex}
CFG="$CH/config.toml"
MANAGED="$DIR/config.managed.toml"
LIST=${HERMES_HOME:-$HOME/.hermes}/skills-library-claude.txt
CHECK=0
case ${1:-} in
  --check) CHECK=1 ;;
  '') ;;
  *) echo "usage: setup-codex.sh [--check]" >&2; exit 2 ;;
esac
umask 077
say() { echo "setup-codex: $*"; }
python3 -c 'import tomllib' 2>/dev/null || { say "needs python3 3.11 or newer (tomllib)"; exit 2; }
command -v codex >/dev/null || { say "codex is not installed (mac.md / desktop.md, \"Codex\")"; exit 2; }
[ -f "$MANAGED" ] || { say "missing $MANAGED"; exit 2; }
mkdir -p "$CH"
rc=0

# 1. the files built from synced sources, and the skill links (Codex reads ~/.agents/skills)
if [ $CHECK = 0 ]; then
  bash "$DIR/build-codex.sh" || { say "build-codex.sh failed"; rc=4; }
  u="${HERMES_HOME:-$HOME/.hermes}/scripts/update-skills-library.sh"
  if [ -f "$u" ]; then bash "$u" --links-only | sed 's/^/  /' || say "WARNING: update-skills-library.sh --links-only failed"
  else say "WARNING: no $u; skills not linked"; fi
else
  bash "$DIR/build-codex.sh" --check || { say "~/.codex/AGENTS.md or a role file is stale (run setup-codex.sh)"; rc=1; }
fi

# 2. render config.toml: drop the old managed blocks, refuse hand-set managed keys, insert the blocks
render="$CH/.config.toml.render.$$"
trap 'rm -f "$render"' EXIT
python3 - "$CFG" "$MANAGED" "$render" "$CH" "$HOME/.agents/skills" <<'PY'
import glob, os, re, sys, tomllib
cfg, managed, out, ch, agents = sys.argv[1:6]
cur = open(cfg).read() if os.path.exists(cfg) else ""
lines = cur.splitlines()
kept, skip, after_top = [], False, False
for l in lines:                                   # strip every managed block, and one blank line after top-level
    if re.match(r"# >>> claude-setup managed: ", l): skip = True; continue
    m = re.match(r"# <<< claude-setup managed: (\S+)", l)
    if m: skip = False; after_top = m.group(1) == "top-level"; continue
    if skip: continue
    if after_top and l.strip() == "": after_top = False; continue
    after_top = False
    kept.append(l)
while kept and kept[-1].strip() == "": kept.pop()
try:
    d = tomllib.loads("\n".join(kept) + "\n")
except tomllib.TOMLDecodeError as e:
    print(f"setup-codex: {cfg} is not valid TOML outside the managed blocks: {e}"); sys.exit(2)
bad = [k for k in ("default_permissions", "project_doc_fallback_filenames", "project_doc_max_bytes", "sandbox_mode") if k in d]
if "sandbox_workspace_write" in d: bad.append("[sandbox_workspace_write]")
if "claude-setup" in d.get("permissions", {}): bad.append("[permissions.claude-setup]")
if bad:
    print("setup-codex: refused, nothing written. Remove or move these from " + cfg + " (outside the managed blocks): " + ", ".join(bad))
    print("setup-codex: config.managed.toml sets them for Justin's setup; to change one, edit that file and rerun.")
    sys.exit(3)
m = open(managed).read()
top = re.search(r"(?ms)^# >>> claude-setup managed: top-level >>>\n.*?^# <<< claude-setup managed: top-level <<<\n", m).group(0)
tables = re.search(r"(?ms)^# >>> claude-setup managed: tables >>>\n.*?^# <<< claude-setup managed: tables <<<\n", m).group(0)
# Q10: a skill an enabled plugin bundles under a name Justin's Hermes skills already use is disabled
extra = []
for key, p in sorted(d.get("plugins", {}).items()):
    if not isinstance(p, dict) or not p.get("enabled") or "@" not in key: continue
    plugin, market = key.split("@", 1)
    for f in sorted(glob.glob(os.path.join(ch, "plugins", "cache", market, plugin, "*", "skills", "*", "SKILL.md"))):
        name = os.path.basename(os.path.dirname(f))
        if os.path.lexists(os.path.join(agents, name)):
            extra.append(f'[[skills.config]]\n# {key} bundles "{name}"; the Hermes skill of that name wins (generated by setup-codex.sh)\npath = "{f}"\nenabled = false\n')
            print(f"setup-codex: plugin {key} skill '{name}' duplicates the Hermes skill: disabled")
if extra:
    end = "# <<< claude-setup managed: tables <<<\n"
    tables = tables[: -len(end)] + "\n" + "\n".join(extra) + end
i = next((n for n, l in enumerate(kept) if re.match(r"^\s*\[", l)), len(kept))
head, rest = kept[:i], kept[i:]
while head and head[-1].strip() == "": head.pop()
parts = ("\n".join(head) + "\n\n" if head else "") + top + "\n" + ("\n".join(rest) + "\n\n" if rest else "") + tables
open(out, "w").write(parts)
r = tomllib.loads(parts)
assert r["default_permissions"] == "claude-setup" and "claude-setup" in r["permissions"], "managed blocks did not load"
PY
prc=$?
[ $prc = 0 ] || exit $prc

if cmp -s "$render" "$CFG"; then
  say "config.toml is current"
elif [ $CHECK = 1 ]; then
  say "config.toml differs from the managed blocks (run setup-codex.sh)"; rc=1
else
  if [ -f "$CFG" ]; then
    mkdir -p "$CH/backups"; b="$CH/backups/config.toml.$(date +%Y%m%d-%H%M%S)"
    cp -p "$CFG" "$b" && chmod 600 "$b" && say "backed up config.toml to $b"
  fi
  mv -f "$render" "$CFG" && say "merged the managed blocks into $CFG"
fi

# 3. check what Codex really loads
t=$(mktemp -d "$CH/.setup-check.XXXXXX"); trap 'rm -f "$render"; rm -rf "$t"' EXIT
(cd "$HOME" && codex doctor --json >"$t/doctor.json" 2>"$t/doctor.err")
if grep -q 'malformed agent role' "$t/doctor.json" 2>/dev/null; then
  say "CHECK FAILED: codex doctor reports a malformed agent role:"; grep -o 'malformed agent role[^"]*' "$t/doctor.json" | head -3; rc=4
fi
if (cd "$HOME" && codex debug prompt-input >"$t/pi.json" 2>"$t/pi.err"); then
  first=$(head -1 "$DIR/agents-header.md")
  jq -r '.[] | .content[]? | .text // empty' "$t/pi.json" >"$t/pi.txt"
  grep -qF -- "$first" "$t/pi.txt" || { say "CHECK FAILED: Codex does not load ~/.codex/AGENTS.md (header line missing)"; rc=4; }
  sed -n 's/^- \([^:]*\): .*(file: r[0-9]*\/.*/\1/p' "$t/pi.txt" | sort >"$t/names"
  if [ -f "$LIST" ]; then
    for n in $(grep -vE '^[[:space:]]*(#|$)' "$LIST" | awk '{print $1}'); do
      c=$(grep -cx -- "$n" "$t/names"); [ "$c" = 1 ] || { say "CHECK FAILED: skill $n is listed $c times"; rc=4; }
    done
  fi
  d=$(uniq -d "$t/names" | tr '\n' ' '); [ -z "$d" ] || { say "CHECK FAILED: listed twice: $d"; rc=4; }
else
  say "CHECK FAILED: codex debug prompt-input: $(head -c 300 "$t/pi.err")"; rc=4
fi
[ $rc = 0 ] && say "checks passed: AGENTS.md loaded, roles valid, each Hermes skill listed once"

if [ $CHECK = 0 ]; then
  echo "Next: open codex, type /hooks and trust the 6 hooks (again after any hooks.json change)."
  [ -f "$CH/auth.json" ] || echo "If Codex is not signed in on this machine yet: codex login"
fi
exit $rc
